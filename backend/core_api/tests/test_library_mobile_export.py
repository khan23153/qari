"""The offline library bundled in the APK must match the backend seed.

`mobile/assets/library/library_seed.json` is what the app serves when the
library API is unreachable or not yet deployed. It is generated by
`scripts/export_library_mobile_seed.py` from the same LibraryService the API
uses; this test fails if either side changes without regenerating it.
"""

import json
from pathlib import Path

import pytest

from app.library.arabic import normalize_arabic
from app.library.mobile_export import build_mobile_seed
from app.library.service import LibraryService

ASSET = Path(__file__).resolve().parents[3] / "mobile" / "assets" / "library" / "library_seed.json"


@pytest.mark.asyncio
async def test_bundled_mobile_seed_matches_backend_export():
    expected = await build_mobile_seed(LibraryService.from_bundled_data())
    assert ASSET.exists(), "run scripts/export_library_mobile_seed.py"
    actual = json.loads(ASSET.read_text(encoding="utf-8"))
    assert actual == expected, "mobile asset is stale: run scripts/export_library_mobile_seed.py"


@pytest.mark.asyncio
async def test_mobile_seed_is_api_shaped_and_complete():
    seed = await build_mobile_seed(LibraryService.from_bundled_data())
    assert seed["version"] == 1
    assert [c["slug"] for c in seed["categories"]] == ["hadith", "tafsir", "fiqh", "rijal", "daif_mawdu"]
    bukhari = next(c for c in seed["collections"] if c["slug"] == "bukhari")
    assert bukhari["book_count"] == 97 and len(bukhari["books"]) == 97
    assert set(seed["hadiths"]) == {"bukhari:1", "abudawud:2201", "tirmidhi:4", "tirmidhi:172"}
    assert [s["id"] for s in seed["hadith_summaries"]] == list(seed["hadiths"])
    t4 = seed["hadiths"]["tirmidhi:4"]
    assert {g["scholar"] for g in t4["grades"]} == {"Ahmad Shakir", "al-Albani", "Zubair 'Ali Za'i"}
    assert seed["narrators"]["sufyan-ibn-uyaynah"]["teachers"][0]["id"] == "yahya-ibn-said-al-ansari"
    niyyah = next(g for g in seed["gharib"] if g["id"] == "niyyah")
    # Forms are pre-normalised so the app's lookup matches the API's exactly.
    assert all(f == normalize_arabic(f) for f in niyyah["forms"])
    assert "matched_form" not in niyyah
